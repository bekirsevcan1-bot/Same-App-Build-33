create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  phone text,
  role text not null default 'customer',
  district text,
  address text,
  id_number text,
  service_areas text[] not null default '{}',
  kvkk_consent boolean not null default false,
  kvkk_consent_at timestamptz,
  kvkk_consent_version text,
  is_approved boolean not null default false,
  is_blocked boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(coalesce(new.email, 'Kullanıcı'), '@', 1), 'Kullanıcı'),
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data->>'role', 'customer')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create table if not exists public.ustas (
  id bigint generated by default as identity primary key,
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  name text not null,
  phone text,
  specialty text not null,
  specialties text[] not null default '{}',
  category_id text not null default 'diger',
  rating numeric not null default 4.5,
  review_count integer not null default 0,
  experience integer not null default 0,
  bio text,
  lat double precision,
  lng double precision,
  is_online boolean not null default false,
  verified boolean not null default false,
  service_areas text[] not null default '{}',
  created_at timestamptz not null default now()
);

create table if not exists public.usta_locations (
