-- Request lifecycle additions. These are intentionally additive so existing
-- requests remain readable after this feature is enabled.
alter table public.requests add column if not exists delivery_status text;
alter table public.requests add column if not exists cancellation_reason text;
alter table public.requests add column if not exists unreachable_reason text;
alter table public.requests add column if not exists rating_protected boolean not null default false;

create table if not exists public.request_events (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.requests(id) on delete cascade,
  actor_id uuid not null references public.profiles(id) on delete cascade,
  action text not null,
  reason text,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  request_id bigint references public.requests(id) on delete cascade,
  title text not null,
  message text not null,
  type text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  session_id text not null,
  sender_name text not null,
  email text,
  message text not null,
  is_agent boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  usta_id bigint not null references public.ustas(id) on delete cascade,
  request_id bigint references public.requests(id) on delete set null,
  rating integer not null check (rating between 1 and 5),
  comment text,
  reviewer_name text not null,
  created_at timestamptz not null default now(),
  unique (usta_id, request_id)
);

