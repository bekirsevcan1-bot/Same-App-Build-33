create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public
as $$
  select exists(
    select 1
    from public.profiles
    where id = auth.uid()
      and not is_blocked
      and (role = 'admin' or lower(email) = 'bekirsevcan1@gmail.com')
  );
$$;

create policy "profiles self or admin read" on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());
create policy "profiles self insert" on public.profiles for insert to authenticated
with check (id = auth.uid());
create policy "profiles self update or admin" on public.profiles for update to authenticated
using (id = auth.uid() or public.is_admin())
with check (id = auth.uid() or public.is_admin());
create policy "verified providers public read" on public.ustas for select to anon, authenticated
using (verified = true or profile_id = auth.uid() or public.is_admin());
create policy "provider self insert" on public.ustas for insert to authenticated
with check (profile_id = auth.uid());
create policy "provider self update or admin" on public.ustas for update to authenticated
using (profile_id = auth.uid() or public.is_admin())
with check (profile_id = auth.uid() or public.is_admin());
create policy "public online locations read" on public.usta_locations for select to anon, authenticated
using (is_online = 'true' or public.is_admin());
create policy "provider own location write" on public.usta_locations for insert to authenticated
with check (exists(select 1 from public.ustas where id = usta_id and profile_id = auth.uid()));
create policy "provider own location update" on public.usta_locations for update to authenticated
using (exists(select 1 from public.ustas where id = usta_id and profile_id = auth.uid()) or public.is_admin());
create policy "request owner or admin read" on public.requests for select to authenticated
using (owner_id = auth.uid() or public.is_admin());
create policy "request owner insert" on public.requests for insert to authenticated
with check (owner_id = auth.uid());
create policy "request owner or admin update" on public.requests for update to authenticated
using (owner_id = auth.uid() or public.is_admin());

-- Assigned providers may update lifecycle fields; the client still validates
-- the allowed action and the event actor is recorded for auditability.
create policy "assigned provider request update" on public.requests for update to authenticated
using (exists (select 1 from public.ustas where id = assigned_usta_id and profile_id = auth.uid()))
with check (exists (select 1 from public.ustas where id = assigned_usta_id and profile_id = auth.uid()));
create policy "request event actor insert" on public.request_events for insert to authenticated
with check (actor_id = auth.uid());
create policy "request owner provider event read" on public.request_events for select to authenticated
using (
  actor_id = auth.uid()
  or exists (select 1 from public.requests r where r.id = request_id and (r.owner_id = auth.uid() or public.is_admin()))
);
create policy "notification recipient read" on public.notifications for select to authenticated
using (recipient_id = auth.uid() or public.is_admin());
create policy "notification recipient update" on public.notifications for update to authenticated
using (recipient_id = auth.uid() or public.is_admin())
with check (recipient_id = auth.uid() or public.is_admin());
create policy "notification insert authenticated" on public.notifications for insert to authenticated
with check (
  exists (
    select 1 from public.requests r
    left join public.ustas u on u.id = r.assigned_usta_id
    where r.id = request_id
      and (r.owner_id = auth.uid() or u.profile_id = auth.uid() or public.is_admin())
      and (recipient_id = r.owner_id or recipient_id = u.profile_id)
  )
);
create policy "support session read" on public.support_messages for select to anon, authenticated
using (true);
create policy "support visitor insert" on public.support_messages for insert to anon, authenticated
with check (is_agent = false);
create policy "support admin reply" on public.support_messages for insert to authenticated
with check (is_agent = true and public.is_admin());

create policy "reviews public read" on public.reviews for select to anon, authenticated
using (true);
create policy "review authenticated insert" on public.reviews for insert to authenticated
with check (
  exists (
    select 1 from public.requests
    where requests.id = request_id and requests.owner_id = auth.uid()
  )
);

